    FinanceIconKey.home => LucideIcons.house500,
    FinanceIconKey.health => LucideIcons.shieldPlus500,
    FinanceIconKey.education => LucideIcons.graduationCap500,
    FinanceIconKey.entertainment => LucideIcons.clapperboard500,
    FinanceIconKey.shopping => LucideIcons.shoppingBag500,
    FinanceIconKey.bills => LucideIcons.receiptText500,
    FinanceIconKey.travel => LucideIcons.plane500,
    FinanceIconKey.gift => LucideIcons.gift500,
    FinanceIconKey.receipt => LucideIcons.receiptText500,
    FinanceIconKey.aiCapture => LucideIcons.sparkles500,
    FinanceIconKey.manualCapture => LucideIcons.notebookPen500,
