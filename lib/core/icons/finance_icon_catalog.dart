/// App-owned meanings for finance icons. Stored category values stay unchanged.
enum FinanceIconKey {
  account,
  transfer,
  budget,
  category,
  income,
  expense,
  food,
  transport,
  home,
  health,
  education,
  entertainment,
  shopping,
  bills,
  travel,
  gift,
  receipt,
  aiCapture,
  manualCapture,
  import,
}

abstract final class FinanceIconCatalog {
  static IconData dataFor(FinanceIconKey key) => switch (key) {
    FinanceIconKey.account => LucideIcons.wallet500,
    FinanceIconKey.transfer => LucideIcons.arrowLeftRight500,
    FinanceIconKey.budget => LucideIcons.piggyBank500,
